  const originalText = new WeakMap();
  const reverseTranslations = Object.fromEntries(Object.entries(translations).map(([english, malay]) => [malay, english]));

  const replaceText = (node, language) => {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const source = originalText.get(node);
    const match = source.match(/^(\s*)([\s\S]*?)(\s*)$/);
    const text = match[2];
    const translated = language === 'ms' ? translations[text] : reverseTranslations[text] || source.trim();
    if (translated) node.nodeValue = `${match[1]}${translated}${match[3]}`;
  };

  let currentLanguage = 'en';

  const translatePage = (language) => {
    currentLanguage = language;
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
      acceptNode: node => node.parentElement && ['SCRIPT', 'STYLE'].includes(node.parentElement.tagName) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT
    });
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(node => replaceText(node, language));
    document.documentElement.lang = language === 'ms' ? 'ms' : 'en';
    localStorage.setItem('osaka-language', language);
    document.querySelectorAll('[data-language-choice]').forEach(button => button.classList.toggle('is-active', button.dataset.languageChoice === language));
  };

